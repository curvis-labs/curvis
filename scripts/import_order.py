"""Regenerate src/curvis/compute/import_order.py, the step-by-step import order the
preloader uses for the heavy modules of the analyses, polars and pyarrow.

    uv run python scripts/import_order.py          # rewrite the file
    uv run python scripts/import_order.py --check  # exit 1 if the file is out of date

Light jobs import their modules on the Qt main thread (see curvis.compute.jobs). One
``import scipy.stats`` takes ~0.6 s, so the preloader imports the packages it is made
of one at a time, dependencies first, and lets the event loop run in between. Which
packages, and in which order, is found here in fresh subprocesses:

1. ``python -X importtime`` lists every module a target loads, each after the modules
   it imports (post-order).
2. Going through that list, a module whose parent package is not loaded yet is left
   out (importing it would run the parent's ``__init__`` and load the whole package).
   The others are imported in order; the ones that load something new are the steps.

Each target is measured on its own, starting from NumPy alone, so the steps of one
target do not assume another target was preloaded. Run this after upgrading SciPy,
lmfit, polars, pyarrow or a library they load; tests/unit/test_compute_preload.py
checks it.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "curvis" / "compute" / "import_order.py"
BASELINE = "numpy"
"""Loaded before any step is measured (the app always has it)."""

_IMPORTTIME = """
import sys
import {baseline}
print("--curvis-mark--", file=sys.stderr, flush=True)
import {target}
"""

_SIMULATE = """
import importlib, json, sys
import {baseline}
steps = []
for name in json.loads(sys.argv[1]):
    if name in sys.modules:
        continue
    parent = name.rpartition(".")[0]
    if parent and parent not in sys.modules:
        continue  # imported as part of its parent package
    try:
        importlib.import_module(name)
    except Exception:
        continue  # an optional dependency that is not installed
    steps.append(name)
print(json.dumps(steps))
"""


IO_TARGETS = ("polars", "pyarrow")
"""Imported by light jobs outside the analyses: the CSV import preview (polars) and
opening a project (pyarrow, through curvis.io.project)."""


def light_targets() -> tuple[str, ...]:
    """The modules light analyses declare in ``imports``, in the order of the analyses,
    then :data:`IO_TARGETS`."""
    from curvis.analysis.base import light_imports

    analyses = light_imports()
    return (*analyses, *(m for m in IO_TARGETS if m not in analyses))


def _python(code: str, *args: str, flags: tuple[str, ...] = ()) -> str:
    """Run ``code`` in a fresh interpreter; return its stdout, or stderr with flags."""
    # Some imports iterate over sets: a fixed hash seed keeps the order the same.
    env = {**os.environ, "PYTHONHASHSEED": "0"}
    run = subprocess.run(
        [sys.executable, *flags, "-c", code, *args],
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
        env=env,
    )
    return run.stderr if flags else run.stdout


def _third_party(name: str) -> bool:
    """Standard-library modules are cheap and differ between platforms: no steps."""
    top = name.partition(".")[0]
    return top not in sys.stdlib_module_names and not top.startswith("_sysconfigdata")


def steps_for(target: str) -> list[str]:
    """The packages to import, in order, so that ``target`` loads a little at a time."""
    stderr = _python(
        _IMPORTTIME.format(baseline=BASELINE, target=target), flags=("-X", "importtime")
    )
    after_mark = stderr.split("--curvis-mark--", 1)[1]
    names = [
        line.split("|")[-1].strip()
        for line in after_mark.splitlines()
        if line.startswith("import time:")
    ]
    names = [n for n in names if n != "imported package" and _third_party(n)]  # no header
    simulated = _python(_SIMULATE.format(baseline=BASELINE), json.dumps([*names, target]))
    steps: list[str] = json.loads(simulated)
    if not steps or steps[-1] != target:
        steps = [s for s in steps if s != target] + [target]
    return steps


def render(order: dict[str, list[str]]) -> str:
    lines = [
        '"""Step-by-step import order of the heavy modules of light jobs, for the preloader.',
        "",
        "Generated by scripts/import_order.py: do not edit. Each target lists the packages",
        "to import, dependencies first, ending with the target. Names that do not exist on",
        'a platform are skipped. See curvis.compute.preload."""',
        "",
        "ORDER: dict[str, tuple[str, ...]] = {",
    ]
    for target, steps in order.items():
        if len(steps) == 1:  # as ruff formats a one-item tuple
            lines.append(f'    "{target}": ("{steps[0]}",),')
            continue
        lines.append(f'    "{target}": (')
        lines += [f'        "{step}",' for step in steps]
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate() -> str:
    return render({target: steps_for(target) for target in light_targets()})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="only check the file")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date: run scripts/import_order.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
