"""Curvis against the R reference fixtures: one test per fixture file.

Fixtures are generated by ``Rscript validation/r/generate_all.R`` and committed, so
these tests do not need R. Never edit a fixture or loosen a tolerance to make a test
pass (CLAUDE.md).
"""

import re
from pathlib import Path

import pytest

from tests.validation.adapters import ADAPTERS
from tests.validation.harness import (
    FIXTURE_DIR,
    REPO_ROOT,
    compare,
    fixture_paths,
    format_report,
    load_fixture,
)
from tests.validation.tolerances import EXCEPTIONS

FIXTURES = fixture_paths()


def fixture_id(path: Path) -> str:
    return f"{path.parent.name}/{path.stem}"


@pytest.mark.parametrize("path", FIXTURES, ids=fixture_id)
def test_matches_r(path: Path) -> None:
    fixture = load_fixture(path)
    run = ADAPTERS.get(fixture.analysis)
    if run is None:
        pytest.fail(f"{fixture.id}: no adapter for {fixture.analysis!r} in adapters.py")
    mismatches = compare(fixture, run(fixture.inputs))
    if mismatches:
        pytest.fail(format_report(fixture, mismatches), pytrace=False)


@pytest.mark.parametrize("path", FIXTURES, ids=fixture_id)
def test_fixture_records_its_origin(path: Path) -> None:
    made = load_fixture(path).generated_by
    assert (REPO_ROOT / made["script"]).is_file(), f"R script {made['script']} is missing"
    assert made["r_version"].startswith("R version ")
    assert made["packages"], "package versions are missing"


def test_there_are_fixtures() -> None:
    assert FIXTURES, f"no fixtures in {FIXTURE_DIR}"


def test_every_adapter_has_fixtures() -> None:
    analyses = {path.parent.name for path in FIXTURES}
    assert set(ADAPTERS) <= analyses, f"adapters without fixtures: {set(ADAPTERS) - analyses}"


def test_tolerance_exceptions_are_documented() -> None:
    text = (Path(__file__).parent / "TOLERANCES.md").read_text(encoding="utf-8")
    documented = set(re.findall(r"`([^`]+:[^`]+)`", text))
    missing = set(EXCEPTIONS) - documented
    assert not missing, f"tolerance exceptions not listed in TOLERANCES.md: {sorted(missing)}"
